var supportedMethods = []string{http.MethodGet, http.MethodPost, http.MethodPut, http.MethodPatch, http.MethodDelete, http.MethodHead, http.MethodOptions}

type generator struct {
	document map[string]any
}

func main() {
	specPath := flag.String("spec", "spec/openapi.yaml", "pinned OpenAPI document")
	outputPath := flag.String("out", "internal/generated/spec_gen.go", "generated Go output")
	manifestPath := flag.String("manifest", "spec/operations.json", "generated operation manifest")
	check := flag.Bool("check", false, "fail if generated files are stale")
	flag.Parse()

	specData, err := os.ReadFile(filepath.Clean(*specPath))
	fatalIf(err)
	var document map[string]any
	fatalIf(yaml.Unmarshal(specData, &document))
	g := generator{document: document}
	operations, err := g.operations()
	fatalIf(err)
	version := nestedString(document, "info", "version")
	digest := sha256.Sum256(specData)
	sha := hex.EncodeToString(digest[:])

	operationJSON, err := json.Marshal(operations)
	fatalIf(err)
	source := fmt.Sprintf(`// Code generated by go generate; DO NOT EDIT.

package generated

import "encoding/json"

const SpecVersion = %q
const SpecSHA256 = %q

var Operations []Operation

func init() {
	if err := json.Unmarshal([]byte(operationsJSON), &Operations); err != nil {
		panic("decode generated Lago operations: " + err.Error())
	}
}

const operationsJSON = %s
`, version, sha, strconv.Quote(string(operationJSON)))
	formatted, err := format.Source([]byte(source))
	fatalIf(err)
	manifest, err := json.MarshalIndent(map[string]any{"spec_version": version, "spec_sha256": sha, "operation_count": len(operations), "operations": operations}, "", "  ")
	fatalIf(err)
	manifest = append(manifest, '\n')

	if *check {
		checkFile(*outputPath, formatted)
		checkFile(*manifestPath, manifest)
		fmt.Printf("generated command tree is current: %d operations, spec %s (%s)\n", len(operations), version, sha)
		return
	}
	// The -out and -manifest paths are typed by the maintainer running `make generate`,
	// so the taint source and the trust boundary are the same person. Nothing an operator
	// or an API response controls reaches either path.
	// #nosec G306,G703 -- generated Go source is a public repository artifact written to a maintainer-supplied path.
	fatalIf(os.WriteFile(filepath.Clean(*outputPath), formatted, 0o644))
	// #nosec G306,G703 -- the generated parity manifest is a public repository artifact written to a maintainer-supplied path.
	fatalIf(os.WriteFile(filepath.Clean(*manifestPath), manifest, 0o644))
	fmt.Printf("generated %d operations from spec %s (%s)\n", len(operations), version, sha)
}

func (g generator) operations() ([]generated.Operation, error) {
	paths, ok := g.document["paths"].(map[string]any)
	if !ok {
		return nil, fmt.Errorf("OpenAPI document has no paths object")
	}
	pathNames := sortedKeys(paths)
	documentationURLs := g.documentationURLs()
	operations := make([]generated.Operation, 0)
	commandOwners := map[string]string{}
	operationIDs := map[string]bool{}
	for _, path := range pathNames {
		pathItem, ok := paths[path].(map[string]any)
		if !ok {
			continue
		}
		pathParameters, err := g.parameters(pathItem["parameters"])
		if err != nil {
			return nil, fmt.Errorf("%s parameters: %w", path, err)
		}
		for _, method := range supportedMethods {
			raw, exists := pathItem[strings.ToLower(method)]
			if !exists {
				continue
			}
			operationMap, ok := raw.(map[string]any)
			if !ok {
				return nil, fmt.Errorf("%s %s operation is not an object", method, path)
			}
			operationID := stringValue(operationMap["operationId"])
			if operationID == "" {
				return nil, fmt.Errorf("%s %s has no operationId", method, path)
			}
			if operationIDs[operationID] {
				return nil, fmt.Errorf("duplicate operationId %q", operationID)
			}
			operationIDs[operationID] = true
			resource := resourceName(operationMap)
			if resource == "" {
				return nil, fmt.Errorf("%s %s has no tag", method, path)
			}
			explicitAction := normalizeName(stringValue(operationMap["x-lago-cli-action"]))
			action := explicitAction
			if action == "" {
				action = derivedAction(operationID, resource, path, stringValue(operationMap["summary"]))
			}
			command := resource + " " + action
			if owner, exists := commandOwners[command]; exists {
				if explicitAction == "" {
					action = qualifiedAction(operationID, resource)
					command = resource + " " + action
				}
				if fallbackOwner, stillExists := commandOwners[command]; stillExists {
					return nil, fmt.Errorf("CLI command collision %q between %s and %s; add x-lago-cli-action to the OpenAPI operations (initial collision with %s)", command, fallbackOwner, operationID, owner)
				}
			}
			commandOwners[command] = operationID
			operationParameters, err := g.parameters(operationMap["parameters"])
			if err != nil {
				return nil, fmt.Errorf("%s: %w", operationID, err)
			}
			parameters := mergeParameters(pathParameters, operationParameters)
			body, err := g.body(operationMap["requestBody"])
			if err != nil {
				return nil, fmt.Errorf("%s request body: %w", operationID, err)
			}
			paginated := false
			for _, parameter := range parameters {
				paginated = paginated || (parameter.In == "query" && (parameter.Name == "page" || parameter.Name == "per_page"))
			}
			lowerAction := strings.ToLower(action)
			operations = append(operations, generated.Operation{
				Resource:    resource,
				Action:      action,
				OperationID: operationID,
				Method:      method,
				Path:        path,
				Summary:     stringValue(operationMap["summary"]),
				Description: stringValue(operationMap["description"]),
				DocsURL:     documentationURLs[resource],
				Parameters:  parameters,
				Body:        body,
				Idempotent:  retryableOperation(operationMap, method),
				Dangerous:   dangerousOperation(operationMap, method, path, lowerAction),
				Paginated:   paginated,
				Mutation:    mutationOperation(method, lowerAction),
			})
		}
	}
	sort.Slice(operations, func(i, j int) bool {
		if operations[i].Resource == operations[j].Resource {
			return operations[i].Action < operations[j].Action
		}
		return operations[i].Resource < operations[j].Resource
	})
	return operations, nil
}

func (g generator) documentationURLs() map[string]string {
	result := map[string]string{}
	tags, _ := g.document["tags"].([]any)
	for _, raw := range tags {
		tag, _ := raw.(map[string]any)
		name := normalizeName(stringValue(tag["name"]))
		external, _ := tag["externalDocs"].(map[string]any)
		if name != "" {
			result[name] = stringValue(external["url"])
		}
	}
	return result
}

func (g generator) parameters(raw any) ([]generated.Parameter, error) {
	items, ok := raw.([]any)
	if raw == nil || !ok {
		return nil, nil
	}
	result := make([]generated.Parameter, 0, len(items))
	for _, item := range items {
		value, ok := item.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("parameter is not an object")
		}
		resolved, err := g.resolve(value)
		if err != nil {
			return nil, err
		}
		schema, _ := resolved["schema"].(map[string]any)
		if schema != nil {
			schema, err = g.resolveSchema(schema)
			if err != nil {
				return nil, err
			}
		}
		name := stringValue(resolved["name"])
		location := stringValue(resolved["in"])
		if name == "" || location == "" {
			return nil, fmt.Errorf("parameter is missing name or in")
		}
		result = append(result, generated.Parameter{
			Name:        name,
			Flag:        normalizeName(strings.TrimSuffix(name, "[]")),
			In:          location,
			Type:        g.schemaType(schema),
			Required:    boolValue(resolved["required"]),
			Description: stringValue(resolved["description"]),
			Enum:        stringSlice(schema["enum"]),
		})
	}
	return result, nil
}

func (g generator) body(raw any) (*generated.Body, error) {
	request, ok := raw.(map[string]any)
	if raw == nil || !ok {
		return nil, nil
	}
	resolved, err := g.resolve(request)
	if err != nil {
		return nil, err
	}
	// OpenAPI defaults requestBody.required to false. The runtime used to demand a body
	// whenever one was declared, which made `invoices void` refuse the very call the spec
	// documents ("when no body parameters are provided, the invoice can be voided").
	bodyRequired := boolValue(resolved["required"])
	content, _ := resolved["content"].(map[string]any)
	jsonContent, _ := content["application/json"].(map[string]any)
	schema, _ := jsonContent["schema"].(map[string]any)
	if schema == nil {
		return &generated.Body{Required: bodyRequired}, nil
	}
	schema, err = g.resolveSchema(schema)
	if err != nil {
		return nil, err
	}
	body := &generated.Body{Required: bodyRequired}
	properties, _ := schema["properties"].(map[string]any)
	required := requiredSet(schema)
	if len(properties) == 1 {
		for name, childRaw := range properties {
			child, _ := childRaw.(map[string]any)
			child, err = g.resolveSchema(child)
			if err != nil {
				return nil, err
			}
			if g.schemaType(child) == "object" {
				body.Wrapper = name
				return body, g.collectFields(body, child, nil, required[name], 0)
			}
		}
	}
	if err := g.collectFields(body, schema, nil, true, 0); err != nil {
		return nil, err
	}
	return body, nil
}

func (g generator) collectFields(body *generated.Body, schema map[string]any, prefix []string, parentRequired bool, depth int) error {
	if depth > 8 {
		return fmt.Errorf("request schema nesting exceeds eight levels")
	}
	properties, _ := schema["properties"].(map[string]any)
	required := requiredSet(schema)
	for _, name := range sortedKeys(properties) {
		child, _ := properties[name].(map[string]any)
		var err error
		child, err = g.resolveSchema(child)
		if err != nil {
			return err
		}
		path := append(append([]string{}, prefix...), name)
		valueType := g.schemaType(child)
		_, nullable := nullableType(child)
		childProperties, _ := child["properties"].(map[string]any)
		additional := child["additionalProperties"] != nil
		if valueType == "object" && len(childProperties) > 0 && !additional {
			if err := g.collectFields(body, child, path, parentRequired && required[name], depth+1); err != nil {
				return err
			}
			continue
		}
		body.Fields = append(body.Fields, generated.Field{
			Path: path,
			Flag: normalizeName(strings.Join(path, "-")),
			Type: valueType,
			// A nullable field listed under `required` means the key must be present, and
			// null satisfies that. `subscriptions update` lists `ending_at` that way and
			// the CLI demanded a value the API does not need. See DECISIONS.md.
			Required:    parentRequired && required[name] && !nullable,
			Nullable:    nullable,
			Complex:     valueType == "object" || valueType == "array" || additional,
			Description: stringValue(child["description"]),
			Enum:        stringSlice(child["enum"]),
		})
	}
	return nil
}

func (g generator) resolve(value map[string]any) (map[string]any, error) {
	reference := stringValue(value["$ref"])
	if reference == "" {
		return value, nil
	}
	resolved, err := g.reference(reference)
	if err != nil {
		return nil, err
	}
	merged := make(map[string]any, len(resolved)+len(value))
	for key, item := range resolved {
		merged[key] = item
	}
	for key, item := range value {
		if key != "$ref" {
			merged[key] = item
		}
	}
	return merged, nil
}

func (g generator) resolveSchema(schema map[string]any) (map[string]any, error) {
	resolved, err := g.resolve(schema)
	if err != nil {
		return nil, err
	}
	allOf, _ := resolved["allOf"].([]any)
	if len(allOf) == 0 {
		return resolved, nil
	}
	merged := map[string]any{}
	mergedProperties := map[string]any{}
	mergedRequired := []any{}
	for key, value := range resolved {
		if key != "allOf" {
			merged[key] = value
		}
	}
	for _, partRaw := range allOf {
		part, _ := partRaw.(map[string]any)
		part, err = g.resolveSchema(part)
		if err != nil {
			return nil, err
		}
		for key, value := range part {
			switch key {
			case "properties":
				for name, property := range value.(map[string]any) {
					mergedProperties[name] = property
				}
			case "required":
				if values, ok := value.([]any); ok {
					mergedRequired = append(mergedRequired, values...)
				}
			default:
				if _, exists := merged[key]; !exists {
					merged[key] = value
				}
			}
		}
	}
	if len(mergedProperties) > 0 {
		merged["properties"] = mergedProperties
	}
	if len(mergedRequired) > 0 {
		merged["required"] = mergedRequired
	}
	return merged, nil
}

func (g generator) reference(reference string) (map[string]any, error) {
	if !strings.HasPrefix(reference, "#/") {
		return nil, fmt.Errorf("external reference %q is not supported in the pinned spec", reference)
	}
	var current any = g.document
	for _, rawComponent := range strings.Split(strings.TrimPrefix(reference, "#/"), "/") {
		component := strings.ReplaceAll(strings.ReplaceAll(rawComponent, "~1", "/"), "~0", "~")
		object, ok := current.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("reference %q traverses a non-object", reference)
		}
		current, ok = object[component]
		if !ok {
			return nil, fmt.Errorf("reference %q does not exist", reference)
		}
	}
	result, ok := current.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("reference %q does not resolve to an object", reference)
	}
	return result, nil
}

func derivedAction(operationID, resource, path, summary string) string {
	pathParts := strings.Split(strings.Trim(path, "/"), "/")
	if len(pathParts) > 0 && normalizeName(pathParts[0]) != resource {
		return qualifiedAction(operationID, resource)
	}
	if len(pathParts) > 1 {
		last := pathParts[len(pathParts)-1]
		if !strings.HasPrefix(last, "{") {
			return normalizeName(last)
		}
		if len(pathParts) > 2 {
			return qualifiedAction(operationID, resource)
		}
	}
	if fields := strings.Fields(summary); len(fields) > 0 {
		switch strings.ToLower(strings.Trim(fields[0], ":")) {
		case "list":
			return "list"
		case "retrieve", "find", "get":
			return "get"
		case "create":
			return "create"
		case "send", "ingest":
			return "send"
		case "update":
			return "update"
		case "delete", "destroy", "remove":
			return "delete"
		case "terminate":
			return "terminate"
		}
	}
	compactResource := strings.ReplaceAll(resource, "-", "")
	candidates := []string{compactResource, singular(compactResource)}
	lowerID := strings.ToLower(operationID)
	for _, candidate := range candidates {
		if candidate == "" || !strings.HasSuffix(lowerID, strings.ToLower(candidate)) {
			continue
		}
		prefix := operationID[:len(operationID)-len(candidate)]
		switch strings.ToLower(prefix) {
		case "findall", "listall", "list":
			return "list"
		case "find", "get", "retrieve":
			return "get"
		case "destroy", "delete", "remove":
			return "delete"
		default:
			if normalized := normalizeName(prefix); normalized != "" {
				return normalized
			}
		}
	}
	return normalizeName(operationID)
}

func qualifiedAction(operationID, resource string) string {
	compactResource := strings.ReplaceAll(resource, "-", "")
	action := operationID
	for _, candidate := range []string{compactResource, singular(compactResource)} {
		if strings.HasSuffix(strings.ToLower(action), strings.ToLower(candidate)) {
			action = action[:len(action)-len(candidate)]
			break
		}
	}
	normalized := normalizeName(action)
	switch {
	case normalized == "find-all":
		return "list"
	case strings.HasPrefix(normalized, "find-all-"):
		return "list-" + strings.TrimPrefix(normalized, "find-all-")
	case normalized == "find":
		return "get"
	case strings.HasPrefix(normalized, "find-"):
		return "get-" + strings.TrimPrefix(normalized, "find-")
	default:
		return normalized
	}
}

func resourceName(operation map[string]any) string {
	tags, _ := operation["tags"].([]any)
	if len(tags) == 0 {
		return ""
	}
	return normalizeName(stringValue(tags[0]))
}

func normalizeName(value string) string {
	var result strings.Builder
	var previous rune
	for _, current := range strings.TrimSpace(value) {
		if current == '_' || current == ' ' || current == '/' || current == '.' {
			if result.Len() > 0 && previous != '-' {
				result.WriteByte('-')
				previous = '-'
			}
			continue
		}
		if unicode.IsUpper(current) && result.Len() > 0 && previous != '-' && (unicode.IsLower(previous) || unicode.IsDigit(previous)) {
			result.WriteByte('-')
		}
		current = unicode.ToLower(current)
		if current == '-' && previous == '-' {
			continue
		}
		result.WriteRune(current)
		previous = current
	}
	return strings.Trim(result.String(), "-")
}

func singular(value string) string {
	switch {
	case strings.HasSuffix(value, "ies"):
		return strings.TrimSuffix(value, "ies") + "y"
	case strings.HasSuffix(value, "sses"):
		return strings.TrimSuffix(value, "es")
	case strings.HasSuffix(value, "s"):
		return strings.TrimSuffix(value, "s")
	default:
		return value
	}
}

func mergeParameters(path, operation []generated.Parameter) []generated.Parameter {
	result := append([]generated.Parameter{}, path...)
	for _, candidate := range operation {
		replaced := false
		for index, existing := range result {
			if existing.Name == candidate.Name && existing.In == candidate.In {
				result[index] = candidate
				replaced = true
				break
			}
		}
		if !replaced {
			result = append(result, candidate)
		}
	}
	return result
}

// schemaType resolves the JSON type a request field is sent as. It is the source of the
// runtime coercion: an integer field is sent as a JSON integer, a boolean as a boolean.
//
// The spec is OpenAPI 3.1, where a nullable field is written as the union
// `type: [integer, 'null']`. The old plain-string read of `type` failed on the list and
// fell through to "string", so `coupons create --amount-cents 1000` sent `"1000"` while
// `add-ons create` sent `1000`. Unions now resolve to their non-null member. A `oneOf` or
// `anyOf` whose members share one scalar type resolves to that type; mixed members
// (`event.timestamp` is `oneOf [integer, string]`) stay "string", which the server
// accepts for both.
func (g generator) schemaType(schema map[string]any) string {
	if schema == nil {
		return "string"
	}
	if base, _ := nullableType(schema); base != "" && base != "null" {
		return base
	}
	if schema["properties"] != nil || schema["additionalProperties"] != nil {
		return "object"
	}
	if schema["items"] != nil {
		return "array"
	}
	for _, key := range []string{"oneOf", "anyOf"} {
		if members, ok := schema[key].([]any); ok && len(members) > 0 {
			return g.unionScalarType(members)
		}
	}
	return "string"
}

// unionScalarType returns the single scalar type shared by every non-null member of a
// oneOf/anyOf, or "string" when the members disagree or are not scalars.
func (g generator) unionScalarType(members []any) string {
	types := map[string]bool{}
	for _, raw := range members {
		member, ok := raw.(map[string]any)
		if !ok {
			return "string"
		}
		resolved, err := g.resolveSchema(member)
		if err != nil {
			return "string"
		}
		base, _ := nullableType(resolved)
		switch base {
		case "integer", "number", "boolean", "string":
			types[base] = true
		case "", "null":
			if resolved["properties"] != nil || resolved["items"] != nil {
				return "string"
			}
		default:
			return "string"
		}
	}
	if len(types) == 1 {
		for name := range types {
			return name
		}
	}
	return "string"
}

// nullableType splits an OpenAPI 3.1 type union. `type: [integer, 'null']` yields
// ("integer", true); a plain `type: integer` yields ("integer", false); a union with more
// than one non-null member, or no type at all, yields ("", nullable) and the caller falls
// back to the structural checks in schemaType.
func nullableType(schema map[string]any) (string, bool) {
	if schema == nil {
		return "", false
	}
	switch typed := schema["type"].(type) {
	case string:
		return typed, typed == "null"
	case []any:
		var members []string
		nullable := false
		for _, member := range typed {
			if name := stringValue(member); name == "null" {
				nullable = true
			} else if name != "" {
				members = append(members, name)
			}
		}
		if len(members) == 1 {
			return members[0], nullable
		}
		return "", nullable
	default:
		return "", false
	}
}

func requiredSet(schema map[string]any) map[string]bool {
	result := map[string]bool{}
	values, _ := schema["required"].([]any)
	for _, value := range values {
		result[stringValue(value)] = true
	}
	return result
}

func stringSlice(raw any) []string {
	values, _ := raw.([]any)
	result := make([]string, 0, len(values))
	for _, value := range values {
		result = append(result, stringValue(value))
	}
	return result
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func stringValue(value any) string {
	result, _ := value.(string)
	return result
}

func boolValue(value any) bool {
	result, _ := value.(bool)
	return result
}

func nestedString(document map[string]any, path ...string) string {
	var current any = document
	for _, component := range path {
		object, _ := current.(map[string]any)
		current = object[component]
	}
	return stringValue(current)
}

func checkFile(path string, expected []byte) {
	actual, err := os.ReadFile(filepath.Clean(path))
	fatalIf(err)
	if !bytes.Equal(actual, expected) {
		fmt.Fprintf(os.Stderr, "%s is stale; run `make generate`\n", path)
		os.Exit(1)
	}
}

func fatalIf(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "generate:", err)
		os.Exit(1)
	}
}

// dangerousOperation reports whether an operation must be confirmation-gated.
//
// HTTP method semantics do not describe billing semantics: PUT /invoices/{id}/finalize
// is idempotent by RFC 9110 and irreversible by accounting. Classification is therefore
// derived from the spec path, not the verb, and defaults to deny: an operation Lago has
// not explicitly declared safe is treated as dangerous. `x-lago-cli-dangerous` is the
// upstream escape hatch, matching the `x-lago-cli-action` precedent in DECISIONS.md.
func dangerousOperation(operation map[string]any, method, path, lowerAction string) bool {
	if explicit, declared := boolExtension(operation, "x-lago-cli-dangerous"); declared {
		return explicit
	}
	if method == http.MethodDelete {
		return true
	}
	return generated.MatchesDestructiveVocabulary(path) || generated.MatchesDestructiveVocabulary(lowerAction)
}

// retryableOperation reports whether the transport may replay an operation on its own,
// Only side-effect-free reads qualify; lago-api reads no Idempotency-Key header.
// PUT and DELETE are idempotent in the RFC sense and still move money in Lago, so they
// are never auto-retried by default; `x-lago-cli-retryable` opts an operation back in.
func retryableOperation(operation map[string]any, method string) bool {
	if explicit, declared := boolExtension(operation, "x-lago-cli-retryable"); declared {
		return explicit
	}
	return method == http.MethodGet || method == http.MethodHead || method == http.MethodOptions
}

// mutationOperation reports whether a command's default table output is the terse
// identifier block rather than the full attribute dump. See DECISIONS.md: an operator
// running a write wants the identifier and the new state, not 40 attributes.
//
// The rule is mechanical so it is predictable from the command name: every write (POST,
// PUT, PATCH, DELETE) is terse except the read-shaped ones whose body is the answer
// (`invoices preview`, `credit-notes estimate`, `events estimate-fees`, downloads and
// payment URLs, `billable-metrics evaluate-expression`) and bulk ingestion whose output
// is a summary (`events send`, `events batch`). State transitions (`invoices finalize`,
// `subscriptions terminate`, `coupons apply`) are terse: `status` is an identifier key,
// so the new state is exactly what the block prints. Widening or narrowing the set is a
// change here, never 100 hand edits at the call sites.
func mutationOperation(method, lowerAction string) bool {
	switch method {
	case http.MethodGet, http.MethodHead, http.MethodOptions:
		return false
	}
	for _, excluded := range readShapedActions {
		if lowerAction == excluded {
			return false
		}
	}
	if strings.HasSuffix(lowerAction, "-url") || strings.HasPrefix(lowerAction, "estimate") || strings.HasSuffix(lowerAction, "-estimate-instant-fees") {
		return false
	}
	return true
}

// readShapedActions are writes whose response is the answer, not a resource: the caller
// asked a question, and reducing the reply to identifiers would delete it.
var readShapedActions = []string{"preview", "estimate", "estimate-fees", "download", "evaluate-expression", "send", "batch"}

func boolExtension(operation map[string]any, key string) (bool, bool) {
	value, exists := operation[key]
	if !exists {
		return false, false
	}
	result, ok := value.(bool)
	return result, ok
}
